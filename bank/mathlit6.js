// Математическая грамотность: жизненные ситуации по шаблонам (ответ вычисляется).
const { series, num } = require('./gen');
const tg = v => `${Math.round(v).toLocaleString('ru-RU')} тг`;

module.exports = [
  // Какая упаковка выгоднее.
  ...series(4101, 6, T => {
    const [ru, kk, un] = T.pick([['молока', 'сүттің', 'л'], ['сока', 'шырынның', 'л'], ['риса', 'күріштің', 'кг'], ['стирального порошка', 'кір жуғыш ұнтақтың', 'кг']]);
    const a = T.pick([0.5, 1, 1.5]), b = T.pick([2, 3, 4.5]), pa = T.int(3, 9) * 100, pb = Math.round(pa * b / a * T.pick([0.8, 0.85, 0.9, 1.1, 1.15]) / 10) * 10;
    const ua = pa / a, ub = pb / b;
    const right = ua < ub ? `${num(a)} ${un} за ${pa} тг` : `${num(b)} ${un} за ${pb} тг`;
    const other = ua < ub ? `${num(b)} ${un} за ${pb} тг` : `${num(a)} ${un} за ${pa} тг`;
    return { ru: `В магазине две упаковки ${ru}: ${num(a)} ${un} за ${pa} тг и ${num(b)} ${un} за ${pb} тг. Какая покупка выгоднее?`, kk: `Дүкенде ${kk} екі қаптамасы бар: ${num(a)} ${un} — ${pa} тг және ${num(b)} ${un} — ${pb} тг. Қайсысын алған тиімді?`,
      right, wrong: [other, 'одинаково', 'нельзя сравнить'], fmt: x => x, okk: x => x.replace(' за ', ' — ').replace('одинаково', 'бірдей').replace('нельзя сравнить', 'салыстыруға болмайды'),
      e: [`Цена за 1 ${un}: ${num(ua)} тг и ${num(ub)} тг.`, `1 ${un} бағасы: ${num(ua)} тг және ${num(ub)} тг.`] };
  }),
  // Средняя скорость.
  ...series(4102, 5, T => {
    const s = T.pick([60, 120, 180, 240]), v1 = T.pick([40, 60, 80]), v2 = T.pick([60, 90, 120]);
    if (v1 === v2) return null;
    const vs = 2 * s / (s / v1 + s / v2);
    return { ru: `Автомобиль проехал ${s} км со скоростью ${v1} км/ч, а обратно — со скоростью ${v2} км/ч. Найдите среднюю скорость на всём пути.`, kk: `Көлік ${s} км жолды ${v1} км/сағ жылдамдықпен жүріп, кері қарай ${v2} км/сағ жылдамдықпен қайтты. Бүкіл жолдағы орташа жылдамдықты табыңыз.`,
      right: vs, wrong: [(v1 + v2) / 2, v1 + v2, Math.max(v1, v2), vs + 5], fmt: v => `${num(v, 1)} км/ч`, okk: x => x.replace('км/ч', 'км/сағ'),
      e: [`Время: ${num(s / v1)} + ${num(s / v2)} = ${num(s / v1 + s / v2)} ч; v = ${2 * s}/${num(s / v1 + s / v2)} ≈ ${num(vs, 1)} км/ч. Среднее арифметическое скоростей здесь не подходит.`, `Уақыт: ${num(s / v1)} + ${num(s / v2)} = ${num(s / v1 + s / v2)} сағ; v = ${2 * s}/${num(s / v1 + s / v2)} ≈ ${num(vs, 1)} км/сағ. Жылдамдықтардың арифметикалық ортасы бұл жерде жарамайды.`] };
  }),
  // Скидка и кэшбэк.
  ...series(4103, 6, T => {
    const P = T.pick([12000, 18000, 25000, 36000, 48000]), d = T.pick([10, 15, 20, 30]), cb = T.pick([2, 3, 5]);
    const pay = P * (1 - d / 100), back = pay * cb / 100;
    return { ru: `Кроссовки стоят ${tg(P)}. Скидка ${d}%, при оплате картой возвращается ${cb}% от уплаченной суммы. Сколько в итоге потратит покупатель?`, kk: `Кроссовка ${tg(P)} тұрады. Жеңілдік ${d}%, картамен төлегенде төленген соманың ${cb}%-ы қайтарылады. Сатып алушы түптеп келгенде қанша жұмсайды?`,
      right: pay - back, wrong: [P * (1 - (d + cb) / 100), pay, P - back, pay + back], fmt: tg,
      e: [`${tg(P)} − ${d}% = ${tg(pay)}; кэшбэк ${tg(back)}; итого ${tg(pay - back)}.`, `${tg(P)} − ${d}% = ${tg(pay)}; кэшбэк ${tg(back)}; барлығы ${tg(pay - back)}.`] };
  }),
  // Время: расписание.
  ...series(4104, 5, T => {
    const h = T.int(6, 20), m = T.pick([0, 15, 20, 35, 40, 50]), dh = T.int(1, 9), dm = T.pick([15, 25, 40, 45, 50]);
    const end = (h * 60 + m + dh * 60 + dm) % (24 * 60);
    const f = x => `${String(Math.floor(x / 60)).padStart(2, '0')}:${String(x % 60).padStart(2, '0')}`;
    return { ru: `Поезд отправился в ${f(h * 60 + m)} и был в пути ${dh} ч ${dm} мин. Во сколько он прибыл?`, kk: `Пойыз ${f(h * 60 + m)}-де жүріп, жолда ${dh} сағ ${dm} мин болды. Ол сағат нешеде келді?`,
      right: f(end), wrong: [f((end + 60) % 1440), f((h * 60 + m + dh * 60 + dm - 100 + 1440) % 1440), f((h * 60 + m + dh * 100 + dm) % 1440), f((end + 1440 - 60) % 1440)], fmt: x => x,
      e: [`${f(h * 60 + m)} + ${dh} ч ${dm} мин = ${f(end)}.`, `${f(h * 60 + m)} + ${dh} сағ ${dm} мин = ${f(end)}.`] };
  }),
  // Пропорция: рецепт / производительность.
  ...series(4105, 5, T => {
    const p = T.pick([4, 5, 6]), n = T.pick([8, 10, 12, 15]), g = T.pick([200, 250, 300, 400, 500]);
    return { ru: `По рецепту на ${p} порций нужно ${g} г муки. Сколько муки нужно на ${n} порций?`, kk: `Рецепт бойынша ${p} порцияға ${g} г ұн қажет. ${n} порцияға қанша ұн қажет?`,
      right: g * n / p, wrong: [g + (n - p) * 10, g * p / n, g * n, g / p], fmt: v => `${num(v)} г`, e: [`${g} : ${p} · ${n} = ${num(g * n / p)} г.`, `${g} : ${p} · ${n} = ${num(g * n / p)} г.`] };
  }),
  // Совместная работа.
  ...series(4106, 4, T => {
    const a = T.pick([3, 4, 6, 10, 12]), b = T.pick([4, 6, 12, 15]);
    if (a === b) return null;
    const t = a * b / (a + b);
    return { ru: `Первая труба наполняет бассейн за ${a} ч, вторая — за ${b} ч. За сколько часов наполнят бассейн обе трубы вместе?`, kk: `Бірінші құбыр бассейнді ${a} сағатта, екіншісі ${b} сағатта толтырады. Екі құбыр бірге бассейнді неше сағатта толтырады?`,
      right: t, wrong: [(a + b) / 2, a + b, Math.abs(a - b), Math.min(a, b) / 2], fmt: v => `${num(v)} ч`, okk: x => x.replace(' ч', ' сағ'),
      e: [`За час: 1/${a} + 1/${b} = ${a + b}/${a * b}; время ${a * b}/${a + b} = ${num(t)} ч.`, `Бір сағатта: 1/${a} + 1/${b} = ${a + b}/${a * b}; уақыт ${a * b}/${a + b} = ${num(t)} сағ.`] };
  }),
  // Среднее и медиана оценок.
  ...series(4107, 5, T => {
    const arr = Array.from({ length: T.pick([5, 7]) }, () => T.int(2, 5));
    const ask = T.pick(['avg', 'med']);
    const sorted = arr.slice().sort((x, y) => x - y), med = sorted[(sorted.length - 1) / 2], avg = arr.reduce((s, x) => s + x, 0) / arr.length;
    return ask === 'avg'
      ? { ru: `Оценки ученика: ${arr.join(', ')}. Найдите средний балл.`, kk: `Оқушының бағалары: ${arr.join(', ')}. Орташа балды табыңыз.`, right: avg, wrong: [med, avg + 0.5, Math.max(...arr) - Math.min(...arr), avg - 0.4], fmt: v => num(v, 2), e: [`Сумма ${arr.reduce((s, x) => s + x, 0)} : ${arr.length} = ${num(avg, 2)}.`, `Қосынды ${arr.reduce((s, x) => s + x, 0)} : ${arr.length} = ${num(avg, 2)}.`] }
      : { ru: `Оценки ученика: ${arr.join(', ')}. Найдите медиану.`, kk: `Оқушының бағалары: ${arr.join(', ')}. Медиананы табыңыз.`, right: med, wrong: [avg, arr[(arr.length - 1) / 2], med + 1, med - 1], fmt: v => num(v, 2), e: [`Упорядочим: ${sorted.join(', ')}; в середине — ${med}.`, `Реттейміз: ${sorted.join(', ')}; ортасында — ${med}.`] };
  })
];
