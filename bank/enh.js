// Помощник для английских переводов: строки идут в том же порядке, что и задания в исходном файле.
// Строка: [вопрос, варианты (0 — как в русской версии), объяснение, левая колонка для соответствия].
const L = (file, rows) => Object.fromEntries(rows.map((r, i) => r && [`${file}#${i}`, { t: r[0], o: r[1] || undefined, e: r[2] || '', l: r[3] || undefined }]).filter(Boolean));
module.exports = { L };
