const { series, num } = require('./gen');
const u = unit => v => `${num(v)} ${unit}`;

// Вещества: формула, молярная масса, название (рус., каз.).
const SUBS = [
  ['H₂O', 18, 'воды', 'су'], ['CO₂', 44, 'углекислого газа', 'көмірқышқыл газы'], ['NaCl', 58.5, 'хлорида натрия', 'натрий хлориді'],
  ['H₂SO₄', 98, 'серной кислоты', 'күкірт қышқылы'], ['CaCO₃', 100, 'карбоната кальция', 'кальций карбонаты'], ['NaOH', 40, 'гидроксида натрия', 'натрий гидроксиді'],
  ['HCl', 36.5, 'хлороводорода', 'хлорсутек'], ['NH₃', 17, 'аммиака', 'аммиак'], ['CH₄', 16, 'метана', 'метан'], ['O₂', 32, 'кислорода', 'оттек'],
  ['Fe₂O₃', 160, 'оксида железа(III)', 'темір(III) оксиді'], ['KOH', 56, 'гидроксида калия', 'калий гидроксиді'], ['CuSO₄', 160, 'сульфата меди(II)', 'мыс(II) сульфаты'],
  ['Al₂O₃', 102, 'оксида алюминия', 'алюминий оксиді'], ['HNO₃', 63, 'азотной кислоты', 'азот қышқылы'], ['C₂H₅OH', 46, 'этанола', 'этанол']
];
const GAS = SUBS.filter(s => ['CO₂', 'NH₃', 'CH₄', 'O₂', 'HCl'].includes(s[0])).concat([['N₂', 28, 'азота', 'азот'], ['H₂', 2, 'водорода', 'сутек'], ['SO₂', 64, 'сернистого газа', 'күкірт диоксиді']]);
// Массовая доля элемента: формула, M, элемент, масса элемента в формуле.
const FRAC = [['H₂O', 18, 'кислорода', 'оттектің', 16], ['CO₂', 44, 'углерода', 'көміртектің', 12], ['CaCO₃', 100, 'кальция', 'кальцийдің', 40], ['Fe₂O₃', 160, 'железа', 'темірдің', 112],
  ['NH₃', 17, 'азота', 'азоттың', 14], ['CH₄', 16, 'углерода', 'көміртектің', 12], ['SO₃', 80, 'серы', 'күкірттің', 32], ['MgO', 40, 'магния', 'магнийдің', 24], ['NaOH', 40, 'натрия', 'натрийдің', 23]];

module.exports = [
  ...series(3101, 8, T => {
    const [f, M, ru, kk] = T.pick(SUBS);
    const n = T.pick([0.1, 0.2, 0.25, 0.5, 1.5, 2, 3]);
    return { ru: `Какова масса ${num(n)} моль ${ru} (${f})?`, kk: `${num(n)} моль ${kk} (${f}) массасы қандай?`, right: n * M, wrong: [M / n, M, n * M * 2, n * 22.4], fmt: u('г'),
      e: [`M(${f}) = ${num(M)} г/моль; m = n·M = ${num(n)}·${num(M)} = ${num(n * M)} г.`, `M(${f}) = ${num(M)} г/моль; m = n·M = ${num(n)}·${num(M)} = ${num(n * M)} г.`] };
  }),
  ...series(3102, 7, T => {
    const [f, M, ru, kk] = T.pick(GAS);
    const n = T.pick([0.1, 0.2, 0.25, 0.5, 1, 2, 3]), m = n * M;
    return { ru: `Какой объём (н. у.) занимают ${num(m)} г ${ru} (${f})?`, kk: `${num(m)} г ${kk} (${f}) қалыпты жағдайда қандай көлем алады?`, right: n * 22.4, wrong: [m * 22.4, 22.4 / n, m / 22.4, n * 22.4 * 2], fmt: u('л'),
      e: [`n = m/M = ${num(m)}/${num(M)} = ${num(n)} моль; V = n·22,4 = ${num(n * 22.4)} л.`, `n = m/M = ${num(m)}/${num(M)} = ${num(n)} моль; V = n·22,4 = ${num(n * 22.4)} л.`] };
  }),
  ...series(3103, 7, T => {
    const [f, M, ru, kk, me] = T.pick(FRAC);
    const w = me / M * 100;
    return { ru: `Вычислите массовую долю ${ru} в ${f}.`, kk: `${f} құрамындағы ${kk} массалық үлесін есептеңіз.`, right: w, wrong: [100 - w, me, w / 2, M - me], fmt: v => `${num(v, 1)}%`,
      e: [`ω = ${me}/${M}·100% ≈ ${num(w, 1)}%.`, `ω = ${me}/${M}·100% ≈ ${num(w, 1)}%.`] };
  }),
  ...series(3104, 6, T => {
    const m = T.pick([50, 80, 100, 150, 200, 250, 400]), w = T.pick([5, 8, 10, 15, 20, 25]);
    const kind = T.pick(['salt', 'water', 'dilute']);
    if (kind === 'salt') return { ru: `Сколько граммов соли нужно для приготовления ${m} г ${w}%-го раствора?`, kk: `${w}%-дық ${m} г ерітінді дайындау үшін неше грамм тұз қажет?`, right: m * w / 100, wrong: [m - m * w / 100, w, m / w, m * w / 10], fmt: u('г'), e: [`m(соли) = ${m}·${w}/100 = ${num(m * w / 100)} г.`, `m(тұз) = ${m}·${w}/100 = ${num(m * w / 100)} г.`] };
    if (kind === 'water') return { ru: `Сколько граммов воды нужно для приготовления ${m} г ${w}%-го раствора соли?`, kk: `${w}%-дық ${m} г тұз ерітіндісін дайындау үшін неше грамм су қажет?`, right: m - m * w / 100, wrong: [m * w / 100, m, m + m * w / 100, m - w], fmt: u('г'), e: [`Соли ${num(m * w / 100)} г, воды ${m} − ${num(m * w / 100)} = ${num(m - m * w / 100)} г.`, `Тұз ${num(m * w / 100)} г, су ${m} − ${num(m * w / 100)} = ${num(m - m * w / 100)} г.`] };
    const add = T.pick([50, 100, 150, 200]);
    const w2 = m * w / (m + add);
    return { ru: `К ${m} г ${w}%-го раствора добавили ${add} г воды. Какой стала массовая доля соли?`, kk: `${w}%-дық ${m} г ерітіндіге ${add} г су қосылды. Тұздың массалық үлесі қандай болды?`, right: w2, wrong: [w * m / add, w / 2, w - add / 100, w], fmt: v => `${num(v, 1)}%`, e: [`Соли ${num(m * w / 100)} г, раствора ${m + add} г: ω = ${num(w2, 1)}%.`, `Тұз ${num(m * w / 100)} г, ерітінді ${m + add} г: ω = ${num(w2, 1)}%.`] };
  }),
  // Расчёт по уравнению: газ из массы металла/соли.
  ...series(3105, 6, T => {
    const R = T.pick([
      ['Zn + 2HCl → ZnCl₂ + H₂↑', 'цинка', 'мырыш', 65, 1, 'водорода', 'сутек'],
      ['Mg + 2HCl → MgCl₂ + H₂↑', 'магния', 'магний', 24, 1, 'водорода', 'сутек'],
      ['CaCO₃ + 2HCl → CaCl₂ + H₂O + CO₂↑', 'карбоната кальция', 'кальций карбонаты', 100, 1, 'углекислого газа', 'көмірқышқыл газы'],
      ['2Na + 2H₂O → 2NaOH + H₂↑', 'натрия', 'натрий', 23, 0.5, 'водорода', 'сутек']
    ]);
    const n = T.pick([0.1, 0.2, 0.4, 0.5, 1]), m = n * R[3];
    const V = n * R[4] * 22.4;
    return { ru: `Какой объём ${R[5]} (н. у.) выделится при реакции ${num(m)} г ${R[1]}? ${R[0]}`, kk: `${num(m)} г ${R[2]} әрекеттескенде қалыпты жағдайда қанша көлем ${R[6]} бөлінеді? ${R[0]}`,
      right: V, wrong: [n * 22.4 * (R[4] === 1 ? 2 : 1), m * 22.4 / 2, V * 2, n * 11.2 * (R[4] === 1 ? 3 : 2)], fmt: u('л'),
      e: [`n = ${num(m)}/${R[3]} = ${num(n)} моль; по уравнению газа ${num(n * R[4])} моль; V = ${num(V)} л.`, `n = ${num(m)}/${R[3]} = ${num(n)} моль; теңдеу бойынша газ ${num(n * R[4])} моль; V = ${num(V)} л.`] };
  })
];
