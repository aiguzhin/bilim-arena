// Биология: решётка Пеннета, цепь питания.
const { S } = require('./h');
const F = require('./fig');
const { K, svg, txt, line, arrow } = F;
const I = (q, img) => ({ ...q, img });

const punnett = (() => {
  const x0 = 90, y0 = 60, c = 70;
  let s = txt(x0 + c * 0.5, y0 - 18, 'A', { b: true }) + txt(x0 + c * 1.5, y0 - 18, 'a', { b: true }) + txt(x0 - 20, y0 + c * 0.5, 'A', { b: true }) + txt(x0 - 20, y0 + c * 1.5, 'a', { b: true });
  const cells = [['AA', 'Aa'], ['Aa', 'aa']];
  cells.forEach((row, i) => row.forEach((v, j) => { s += `<rect x="${x0 + j * c}" y="${y0 + i * c}" width="${c}" height="${c}" fill="${v === 'aa' ? K.fill : K.card}" stroke="${K.ink}" stroke-width="2"/>` + txt(x0 + j * c + c / 2, y0 + i * c + c / 2, v, { b: true, size: 16 }); }));
  s += txt(x0 + c, 22, '♂ Aa', { size: 13, c: K.soft }) + txt(30, y0 + c, '♀ Aa', { size: 13, c: K.soft });
  return svg(280, 220, s);
})();
const chain = svg(380, 90, ['A', 'B', 'C', 'D'].map((n, i) => `<circle cx="${40 + i * 100}" cy="45" r="24" fill="${K.fill}" stroke="${K.ink}" stroke-width="2"/>` + txt(40 + i * 100, 45, n, { b: true })
  + (i < 3 ? arrow(66 + i * 100, 45, 112 + i * 100, 45, { c: K.green }) : '')).join(''));

module.exports = [
  I(S('По решётке Пеннета определите вероятность появления потомков с рецессивным признаком.', 'Пеннет торы бойынша рецессивті белгісі бар ұрпақтың пайда болу ықтималдығын анықтаңыз.', ['25%', '50%', '75%', '0%'], null, 0,
    'Генотип aa — одна клетка из четырёх: 1/4 = 25%.', 'aa генотипі — төрт тордың біреуі: 1/4 = 25%.'), punnett),
  I(S('По решётке Пеннета определите расщепление по генотипу.', 'Пеннет торы бойынша генотип бойынша ажырауды анықтаңыз.', ['1 : 2 : 1', '3 : 1', '1 : 1', '9 : 3 : 3 : 1'], null, 0,
    'AA : Aa : aa = 1 : 2 : 1.', 'AA : Aa : aa = 1 : 2 : 1.'), punnett),
  I(S('На схеме цепи питания: A — растения, B — кузнечик, C — лягушка, D — уж. Какое звено — консумент II порядка?', 'Қоректену тізбегінің сызбасында: A — өсімдіктер, B — шегіртке, C — бақа, D — сарыбас жылан. Қай буын — II реттік консумент?', ['C', 'B', 'D', 'A'], null, 0,
    'Продуцент — A, консумент I порядка — B, консумент II порядка — C.', 'Продуцент — A, I реттік консумент — B, II реттік консумент — C.'), chain)
];
