// Биология: задачи по молекулярной биологии и генетике по шаблонам (ответ вычисляется).
const { series } = require('./gen');

const COMP = { А: 'Т', Т: 'А', Г: 'Ц', Ц: 'Г' };
const RNA = { А: 'У', Т: 'А', Г: 'Ц', Ц: 'Г' };
const strand = (T, n) => Array.from({ length: n }, () => T.pick(['А', 'Т', 'Г', 'Ц'])).join('');
const fmt = s => s.match(/.{1,3}/g).join('-');

module.exports = [
  // Комплементарная цепь ДНК.
  ...series(5101, 6, T => {
    const s = strand(T, 9), c = s.split('').map(x => COMP[x]).join('');
    const rev = c.split('').reverse().join(''), rna = s.split('').map(x => RNA[x]).join(''), same = s;
    return { ru: `Участок цепи ДНК: ${fmt(s)}. Какова последовательность комплементарной цепи ДНК?`, kk: `ДНҚ тізбегінің бөлігі: ${fmt(s)}. Комплементар ДНҚ тізбегінің реттілігі қандай?`,
      right: fmt(c), wrong: [fmt(rna), fmt(rev), fmt(same), fmt(c.replace(/Г/g, 'X').replace(/Ц/g, 'Г').replace(/X/g, 'Ц'))], fmt: x => x,
      e: ['Комплементарность: А–Т, Г–Ц.', 'Комплементарлық: А–Т, Г–Ц.'] };
  }),
  // Транскрипция: иРНК по ДНК.
  ...series(5102, 6, T => {
    const s = strand(T, 9), r = s.split('').map(x => RNA[x]).join(''), c = s.split('').map(x => COMP[x]).join('');
    return { ru: `Участок матричной цепи ДНК: ${fmt(s)}. Какая иРНК будет на нём синтезирована?`, kk: `ДНҚ-ның матрицалық тізбегінің бөлігі: ${fmt(s)}. Онда қандай иРНҚ түзіледі?`,
      right: fmt(r), wrong: [fmt(c), fmt(s.replace(/Т/g, 'У')), fmt(r.split('').reverse().join('')), fmt(c.replace(/Т/g, 'У').replace(/А/g, 'Т'))], fmt: x => x,
      e: ['В РНК вместо тимина — урацил: А→У, Т→А, Г→Ц, Ц→Г.', 'РНҚ-да тиминнің орнына урацил: А→У, Т→А, Г→Ц, Ц→Г.'] };
  }),
  // Правило Чаргаффа: доли нуклеотидов.
  ...series(5103, 6, T => {
    const a = T.pick([10, 15, 18, 20, 22, 26, 30, 35]), ask = T.pick(['Г', 'Т', 'Ц']);
    const right = ask === 'Т' ? a : 50 - a;
    return { ru: `В молекуле ДНК адениловые нуклеотиды составляют ${a}%. Сколько процентов составляют нуклеотиды с ${ask === 'Г' ? 'гуанином' : ask === 'Т' ? 'тимином' : 'цитозином'}?`, kk: `ДНҚ молекуласында аденилді нуклеотидтер ${a}% құрайды. ${ask === 'Г' ? 'Гуанинді' : ask === 'Т' ? 'Тиминді' : 'Цитозинді'} нуклеотидтер неше пайыз құрайды?`,
      right, wrong: [100 - a, 100 - 2 * a, ask === 'Т' ? 50 - a : a, right / 2], fmt: v => `${v}%`,
      e: [`А = Т = ${a}%, Г + Ц = ${100 - 2 * a}%, Г = Ц = ${50 - a}%.`, `А = Т = ${a}%, Г + Ц = ${100 - 2 * a}%, Г = Ц = ${50 - a}%.`] };
  }),
  // Моногибридное скрещивание.
  ...series(5104, 6, T => {
    const P = T.pick([['Aa × Aa', '3 : 1', '1 : 2 : 1', 75], ['Aa × aa', '1 : 1', '1 : 1', 50], ['AA × aa', '100% доминантных', '100% Aa', 100], ['AA × Aa', '100% доминантных', '1 : 1', 100]]);
    const ask = T.pick(['ph', 'pct']);
    if (ask === 'ph') return { ru: `Каким будет расщепление по фенотипу при скрещивании ${P[0]} (полное доминирование)?`, kk: `${P[0]} будандастыруында (толық доминанттылық) фенотип бойынша ажырау қандай болады?`,
      right: P[1], wrong: ['3 : 1', '1 : 1', '1 : 2 : 1', '100% доминантных', '9 : 3 : 3 : 1'], fmt: x => x, okk: x => x.replace('доминантных', 'доминантты'),
      e: [`Решётка Пеннета для ${P[0]}: по генотипу ${P[2]}.`, `${P[0]} үшін Пеннет торы: генотип бойынша ${P[2]}.`] };
    return { ru: `Какова вероятность рождения потомка с доминантным признаком при скрещивании ${P[0]}?`, kk: `${P[0]} будандастыруында доминантты белгісі бар ұрпақтың туу ықтималдығы қандай?`,
      right: P[3], wrong: [25, 50, 75, 100, 0], fmt: v => `${v}%`, e: [`Для ${P[0]} доля доминантного фенотипа — ${P[3]}%.`, `${P[0]} үшін доминантты фенотип үлесі — ${P[3]}%.`] };
  }),
  // Длина и масса гена/белка.
  ...series(5105, 5, T => {
    const aa = T.pick([100, 150, 200, 250, 300, 420]);
    const ask = T.pick(['nuc', 'len']);
    if (ask === 'nuc') return { ru: `Белок состоит из ${aa} аминокислот. Сколько нуклеотидов содержит участок двухцепочечной ДНК, кодирующий этот белок (без стоп-кодона)?`, kk: `Белок ${aa} аминқышқылынан тұрады. Осы белокты кодтайтын қос тізбекті ДНҚ бөлігінде неше нуклеотид бар (стоп-кодонсыз)?`,
      right: aa * 6, wrong: [aa * 3, aa * 2, aa, aa * 9], e: [`Одна цепь: ${aa}·3 = ${aa * 3}; две цепи: ${aa * 6}.`, `Бір тізбек: ${aa}·3 = ${aa * 3}; екі тізбек: ${aa * 6}.`] };
    return { ru: `Белок состоит из ${aa} аминокислот. Какова длина кодирующего его гена, если расстояние между нуклеотидами 0,34 нм?`, kk: `Белок ${aa} аминқышқылынан тұрады. Нуклеотидтер арасы 0,34 нм болса, оны кодтайтын геннің ұзындығы қандай?`,
      right: Math.round(aa * 3 * 0.34 * 10) / 10, wrong: [Math.round(aa * 0.34 * 10) / 10, Math.round(aa * 6 * 0.34 * 10) / 10, aa * 3, Math.round(aa * 3 * 0.34 / 2 * 10) / 10], fmt: v => `${String(v).replace('.', ',')} нм`,
      e: [`${aa}·3 = ${aa * 3} нуклеотида; ${aa * 3}·0,34 = ${String(Math.round(aa * 3 * 0.34 * 10) / 10).replace('.', ',')} нм.`, `${aa}·3 = ${aa * 3} нуклеотид; ${aa * 3}·0,34 = ${String(Math.round(aa * 3 * 0.34 * 10) / 10).replace('.', ',')} нм.`] };
  }),
  // Цепь питания.
  ...series(5106, 4, T => {
    const top = T.pick([1, 2, 5, 10]), lv = T.pick([3, 4]);
    const chain = lv === 3 ? ['растения', 'зайцы', 'лиса'] : ['фитопланктон', 'зоопланктон', 'рыба', 'тюлень'];
    const chk = lv === 3 ? ['өсімдіктер', 'қояндар', 'түлкі'] : ['фитопланктон', 'зоопланктон', 'балық', 'итбалық'];
    const need = top * 10 ** (lv - 1);
    return { ru: `Цепь питания: ${chain.join(' → ')}. Сколько килограммов продуцентов нужно, чтобы ${chain[lv - 1]} ${lv === 3 ? 'набрала' : 'набрал'} ${top} кг массы (правило 10%)?`, kk: `Қоректік тізбек: ${chk.join(' → ')}. ${chk[lv - 1]} ${top} кг салмақ қосуы үшін неше килограмм продуцент қажет (10% ережесі)?`,
      right: need, wrong: [need / 10, need * 10, top * 10 * lv, top * 100 + 1], fmt: v => `${v} кг`, e: [`Каждый уровень вверх — в 10 раз меньше: ${top}·10${lv === 3 ? '²' : '³'} = ${need} кг.`, `Әр деңгей жоғары — 10 есе аз: ${top}·10${lv === 3 ? '²' : '³'} = ${need} кг.`] };
  })
];
