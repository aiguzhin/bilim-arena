  const KEEP = new Set(['Кожа', 'Мырза', 'Али', 'Гали', 'Аль-Фараби', 'Навои', 'Мукими', 'Хаджи', 'Ата', 'Би', 'Батыр']);

  // Родительный падеж (рус.) → именительный: «Талгата» → «Талгат», «Абая» → «Абай», «Алии Молдагуловой» → «Алия Молдагулова».
  function nom(w, female) {
    if (KEEP.has(w) || /^[A-ZА-ЯЁӘІҢҒҮҰҚӨҺ]\.$/.test(w) || !/[а-яёәіңғүұқөһ]$/.test(w)) return w;
    if (/(улы|ұлы|ули|қызы|кызы)$/.test(w)) return w;
    let m;
    if ((m = w.match(/^(.*)(ов|ев|ёв|ин|ын|ск|цк)ой$/))) return m[1] + m[2] + (m[2] === 'ск' || m[2] === 'цк' ? 'ая' : 'а');
    if ((m = w.match(/^(.*)(ск|цк|зк|ьк)ого$/))) return m[1] + m[2] + (m[2] === 'ьк' ? 'ий' : 'ий');
    if ((m = w.match(/^(.*)(ов|ев|ёв|ин|ын)а$/))) return m[1] + m[2];
    if ((m = w.match(/^(.*[аеёиоуыэюяәіүұө])я$/))) return m[1] + 'й';
    if (!female && (m = w.match(/^(.*[бвгджзклмнпрстфхцчшщ])я$/))) return m[1] + 'ь';
    if ((m = w.match(/^(.*)ии$/))) return m[1] + 'ия';
    if (female) { if ((m = w.match(/^(.*[^аеёиоуыэюяәіүұө])ы$/))) return m[1] + 'а'; return w; }
    if ((m = w.match(/^(.*[бвгджзклмнпрстфхцчшщқғңһ])ы$/))) return m[1] + 'а';
    if ((m = w.match(/^(.*[бвгджзклмнпрстфхцчшщқғңһ])а$/))) return m[1];
    return w;
  }
  function person(x) {
    const toks = x.replace(/([A-ZА-ЯЁӘІҢҒҮҰҚӨҺ]\.)(?=\S)/g, '$1 ').trim().split(/\s+/);
    if (toks.some(t => /^[а-яё]/.test(t) && !/^аль-/.test(t))) return null; // «имени академика…», «бен» и т. п. — не переводим
    const female = toks.some(t => /(ов|ев|ёв|ин|ын|ск|цк)ой$/.test(t));
    return toks.map(t => nom(t, female)).join(' ');
  }
  // Притяжательная форма для названия с собственным именем: «DAMU мектебі», «Zerde мектеп-гимназиясы».
  function poss(kind) {
    if (/мектеп$/.test(kind)) return kind.replace(/мектеп$/, 'мектебі');
    if (/гимназия$/.test(kind)) return kind + 'сы';
    if (/лицей$/.test(kind)) return kind + 'і';
    if (/интернат$/.test(kind)) return kind + 'ы';
    return kind;
  }
